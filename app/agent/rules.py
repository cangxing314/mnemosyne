"""规则引擎：按玩家说的话查表，自动调整信任值。

不用 LLM 是为了确定性——评测里有"玩家说 X，trust 必须变 Y"这类断言，
模型自由发挥对不上。
"""

# [(触发短语列表, trust 变化量, 原因文案), ...]
# 短语宁可窄：写"黑斗篷的人"不写"黑斗篷"，否则"卖不卖黑斗篷"也算线索；残余误报暂接受。
TRUST_RULES = [
    (["见过阿福", "阿福的消息", "你徒弟", "披黑斗篷", "黑斗篷的人",
      "斗篷的人", "邻镇见过", "去了王都", "往王都"], +2, "玩家提供了阿福的线索"),
    (["帮工", "帮忙", "拉风箱", "送信", "干活", "打下手"], +1, "玩家主动提出帮工"),
    (["便宜", "少点", "砍价", "优惠", "赊账"], -1, "玩家砍价"),
    (["卷款", "偷钱", "跑了", "跑路"], -3, "玩家说阿福坏话"),
]


def judge_relationship_change(user_text: str):
    """返回 (delta, reason)，没命中是 (0, None)。

    从上往下查、命中第一条就返回，所以表的顺序即优先级；同时命中多条只算第一条。
    """
    for patterns, delta, reason in TRUST_RULES:
        if any(p in user_text for p in patterns):
            return delta, reason
    return 0, None
